"""Record every Choice Champs line in a natural voice with Kokoro (open-source TTS).

Writes audio/<hash>.mp3 for each line from list-lines.js and audio/manifest.js.
Lines that already have a file are skipped, so after editing stories just rerun it.
Pass --voice to change voices (that re-records everything).

Setup (once):
  python3 -m venv venv && ./venv/bin/pip install kokoro-onnx soundfile
  curl -LO https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/kokoro-v1.0.onnx
  curl -LO https://github.com/thewh1teagle/kokoro-onnx/releases/download/model-files-v1.0/voices-v1.0.bin
Run (needs ffmpeg):
  node tools/list-lines.js > /tmp/lines.json
  ./venv/bin/python tools/make-voice.py /tmp/lines.json --models <dir with the two model files>
"""
import argparse, json, os, subprocess, tempfile
import soundfile as sf
from kokoro_onnx import Kokoro

ap = argparse.ArgumentParser()
ap.add_argument("lines")
ap.add_argument("--models", default=".")
ap.add_argument("--voice", default=None, help="Kokoro voice, e.g. af_heart, af_bella, am_michael")
ap.add_argument("--speed", type=float, default=0.92)
a = ap.parse_args()

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "audio")
os.makedirs(root, exist_ok=True)
info_path = os.path.join(root, "voice.json")
info = json.load(open(info_path)) if os.path.exists(info_path) else {}
voice = a.voice or info.get("voice", "af_heart")
redo = info.get("voice") not in (None, voice) or info.get("speed") not in (None, a.speed)

lines = json.load(open(a.lines))
k = Kokoro(os.path.join(a.models, "kokoro-v1.0.onnx"), os.path.join(a.models, "voices-v1.0.bin"))
keep = {l["hash"] for l in lines}
for f in os.listdir(root):  # drop recordings of lines the game no longer says
    if f.endswith(".mp3") and (f[:-4] not in keep or redo):
        os.remove(os.path.join(root, f))

todo = [l for l in lines if not os.path.exists(os.path.join(root, l["hash"] + ".mp3"))]
print(f"{len(lines)} lines, {len(todo)} to record with {voice}")
with tempfile.TemporaryDirectory() as tmp:
    for i, l in enumerate(todo, 1):
        samples, sr = k.create(l["text"], voice=voice, speed=a.speed, lang="en-us")
        wav = os.path.join(tmp, "x.wav")
        sf.write(wav, samples, sr)
        subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", wav,
                        "-af", "silenceremove=start_periods=1:start_threshold=-50dB,areverse,silenceremove=start_periods=1:start_threshold=-50dB,areverse,apad=pad_dur=0.25",
                        "-ac", "1", "-b:a", "48k", os.path.join(root, l["hash"] + ".mp3")], check=True)
        if i % 25 == 0: print(f"  {i}/{len(todo)}", flush=True)

with open(os.path.join(root, "manifest.js"), "w") as f:
    f.write("// Generated by tools/make-voice.py: which lines have a recording.\nwindow.CC_CLIPS = ")
    json.dump({l["hash"]: 1 for l in sorted(lines, key=lambda l: l["hash"])}, f, separators=(",", ":"))
    f.write(";\n")
json.dump({"voice": voice, "speed": a.speed}, open(info_path, "w"))
print("done")
